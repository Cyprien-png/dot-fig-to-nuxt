import { textStyleToCss } from '../css/nodeStyle.ts'
import { slugify } from '../design/traverse.ts'
import type { DesignSummary } from '../extract/analyze.ts'
import { ICON_FONTS } from '../extract/iconLibraries.ts'

/** `design/theme.json`: the part of the design the Nuxt configuration consumes. */
export interface ProjectTheme {
  fonts: { name: string; weights: number[]; styles: ('normal' | 'italic')[] }[]
  iconCollections: string[]
}

const isIconFont = (family: string) => ICON_FONTS.some(({ pattern }) => pattern.test(family))

export function buildTheme(summary: DesignSummary): ProjectTheme {
  return {
    fonts: summary.typography.families
      .filter((family) => !isIconFont(family.family))
      .map((family) => ({ name: family.family, weights: family.weights, styles: family.italic ? ['normal', 'italic'] : ['normal'] })),
    iconCollections: summary.iconLibraries.map((library) => library.prefix),
  }
}

const number = (value: number) => String(value).replace('.', '_')

/**
 * Renders the design tokens as CSS custom properties plus one utility class
 * per text style. The file is regenerated on every design import.
 */
export function buildTokensCss(summary: DesignSummary, version: number): string {
  const lines = [
    `/* Generated by dot-fig-to-nuxt from design v${version} of "${summary.name}". */`,
    '/* Do not edit: import a new design version to refresh it. */',
    '',
    ':root {',
  ]
  for (const color of summary.colors) lines.push(`  --${color.token}: ${color.value};`)
  if (summary.colors.length) lines.push('')
  for (const family of summary.typography.families) lines.push(`  --font-${slugify(family.family)}: "${family.family}", sans-serif;`)
  if (summary.typography.families.length) lines.push('')
  for (const radius of summary.radii) lines.push(`  --radius-${number(radius.value)}: ${radius.value}px;`)
  if (summary.radii.length) lines.push('')
  for (const space of summary.spacing) lines.push(`  --space-${number(space.value)}: ${space.value}px;`)
  lines.push('}', '')

  for (const style of summary.typography.styles) {
    const css = textStyleToCss({ ...style, fontStyle: '', textAlign: 'LEFT', verticalAlign: 'TOP', textCase: 'ORIGINAL', textDecoration: 'NONE' })
    css['font-family'] = `var(--font-${slugify(style.fontFamily)})`
    lines.push(`.${style.token} {`, ...Object.entries(css).map(([property, value]) => `  ${property}: ${value};`), '}', '')
  }
  return lines.join('\n')
}
